export const BS_MONTH_NAMES = [
  'Baishakh','Jestha','Ashadh','Shrawan','Bhadra','Ashwin',
  'Kartik','Mangsir','Poush','Magh','Falgun','Chaitra',
];
export const BS_MONTH_NAMES_NE = [
  'बैशाख','जेठ','असार','साउन','भदौ','असोज','कात्तिक','मंसिर','पुष','माघ','फागुन','चैत',
];

const DAY_MS = 86400000;

/** @returns {{year:number, month:number, day:number}} month is 1-12 */
export function adToBs(date) {
  const d = date instanceof Date ? date : new Date(date);
  const utc = Date.UTC(d.getUTCFullYear(), d.getUTCMonth(), d.getUTCDate());
  let remaining = Math.floor((utc - AD_REFERENCE) / DAY_MS);
  if (remaining < 0) throw new RangeError('Date is before the supported BS range (1943-04-14)');

  let year = BS_START_YEAR;
  let month = 1;
  while (true) {
    const months = BS_MONTH_DAYS[year];
    if (!months) throw new RangeError(`BS year ${year} is outside the supported range`);
    const days = months[month - 1];
    if (remaining < days) break;
    remaining -= days;
    month += 1;
    if (month > 12) { month = 1; year += 1; }
  }
  return { year, month, day: remaining + 1 };
}

/** @returns {Date} UTC midnight of the corresponding AD date */
export function bsToAd(year, month, day) {
  let days = 0;
  for (let y = BS_START_YEAR; y < year; y += 1) {
    const months = BS_MONTH_DAYS[y];
    if (!months) throw new RangeError(`BS year ${y} is outside the supported range`);
    days += months.reduce((a, b) => a + b, 0);
  }
  const months = BS_MONTH_DAYS[year];
  if (!months) throw new RangeError(`BS year ${year} is outside the supported range`);
  for (let m = 1; m < month; m += 1) days += months[m - 1];
  days += day - 1;
  return new Date(AD_REFERENCE + days * DAY_MS);
}

/** "2082-05-16" */
export function formatBs(date, { locale = 'en', long = false } = {}) {
  const { year, month, day } = adToBs(date);
  if (!long) return `${year}-${String(month).padStart(2, '0')}-${String(day).padStart(2, '0')}`;
  const names = locale === 'ne' ? BS_MONTH_NAMES_NE : BS_MONTH_NAMES;
  return `${day} ${names[month - 1]} ${year}`;
}

/**
 * Nepali fiscal year runs Shrawan 1 (month 4) to Ashadh end (month 3).
 * FY 2082/83 starts on Shrawan 1, 2082. Returns the starting BS year.
 */
export function fiscalYear(date = new Date()) {
  const { year, month } = adToBs(date);
  return month >= 4 ? year : year - 1;
}

export const fiscalYearLabel = (date = new Date()) => {
  const fy = fiscalYear(date);
  return `${fy}/${String((fy + 1) % 100).padStart(2, '0')}`;
};
